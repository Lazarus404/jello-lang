"""Write src/frontend/syntax/UnicodeWidth.jello (to stdout) from the vendored UCD.

Reads only third_party/ucd, so the output depends on the pinned Unicode
version and nothing on this machine. Zero width is Mn, Me and Cf; wide is
East Asian Wide (W) and Fullwidth (F), minus anything zero width. Only the
files' explicit lines count (no @missing defaults). Adjacent ranges merge.

Usage: scripts/gen_unicode_width.py > src/frontend/syntax/UnicodeWidth.jello
"""
import os
import re

UCD = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "third_party", "ucd")
LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)")


def read(name, wanted):
    version = None
    points = set()
    with open(os.path.join(UCD, name), encoding="utf-8") as f:
        for line in f:
            if version is None:
                version = re.search(r"-(\d+\.\d+\.\d+)\.txt", line).group(1)
            m = LINE.match(line)
            if m and m.group(3) in wanted:
                first = int(m.group(1), 16)
                points.update(range(first, int(m.group(2) or m.group(1), 16) + 1))
    return version, points


def ranges(points):
    out = []
    for cp in sorted(points):
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def literal(rs):
    return '"' + "".join("%06x%06x" % (a, b) for a, b in rs) + '"'


def main():
    v1, zero = read("DerivedGeneralCategory.txt", {"Mn", "Me", "Cf"})
    v2, wide = read("EastAsianWidth.txt", {"W", "F"})
    assert v1 == v2, (v1, v2)
    zero_ranges, wide_ranges = ranges(zero), ranges(wide - zero)
    # Source._codepointWidth's ASCII fast path skips the tables below U+0080.
    assert min(zero_ranges[0][0], wide_ranges[0][0]) >= 0x80
    print(f"""package frontend.syntax;

/** @file
 * Generated by scripts/gen_unicode_width.py from Unicode {v1} (third_party/ucd/
 * DerivedGeneralCategory.txt and EastAsianWidth.txt). Do not edit: test_jello.sh regenerates
 * this file and fails on any difference.
 *
 * The display-width tables that `Source.sourceDiagnostic` uses to align its caret. Each table is
 * text rather than an array literal, so the module initialiser stays one constant per table. It
 * holds sorted, disjoint code-point ranges of 12 lower-case hex digits each: six for the first
 * code point and six for the last. Both tables start above U+007F, which the ASCII fast path in
 * `Source._codepointWidth` relies on. */

/** The code points of general categories Mn, Me and Cf, which take no columns: {len(zero_ranges)} ranges. */
export let zeroWidthRanges: Bytes = {literal(zero_ranges)};

/** The East Asian Wide (W) and Fullwidth (F) code points, less the zero-width ones, which take two
 * columns: {len(wide_ranges)} ranges. */
export let wideRanges: Bytes = {literal(wide_ranges)};""")


main()
